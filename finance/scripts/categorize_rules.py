def is_internal(description: str) -> bool:
    d = description.lower()
    if any(marker in d for marker in INTERNAL_MARKERS):
        return True
    d_digits = re.sub(r"\D", "", d)
    for r in INTERNAL_KNOWN_RECIPIENTS:
        r_digits = re.sub(r"\D", "", r)
        if r_digits and r_digits in d_digits:
            return True
    return False


