DELIBERATELY_UNRESOLVED = [
    "дигит про",  # 9 750 ₽, сама не вспомнила, что за печать (сессия 27.09.2026)
]


def categorize(account: str, date: str, description: str, amount: float,
               mcc: str | None = None) -> str:
    """
    Возвращает строку категории. Категории с префиксом "?" — не разобрано,
    показать Марии на разметку (лист "Не восстановлено — детально").
    """
    d = description.lower()

    if is_internal(description):
        return "внутренний перевод (исключено) — себе / между своими банками"

    for marker in DELIBERATELY_UNRESOLVED:
        if marker in d:
            return f"? уточнить: {marker} (сознательно оставлено Марией)"

    for pattern, category in CREDIT_PATTERNS:
        if re.search(pattern, d):
            return category

    d_digits = re.sub(r"\D", "", d)
    for key, category in KNOWN_PEOPLE_MAP.items():
        key_lower = key.lower()
        if key_lower in d:
            return category
        key_digits = re.sub(r"\D", "", key_lower)
        # only treat as a phone-number match if the key is mostly digits
        # (10-11 digits) — avoids false positives on short numeric fragments
        if len(key_digits) >= 10 and key_digits in d_digits:
            return category

    if mcc and mcc in MCC_MAP:
        return MCC_MAP[mcc]

    for keywords, category in KEYWORD_MAP:
        if any(k in d for k in keywords):
            return category

    if "заработная плата" in d or "зарплата" in d:
        return "ДОХОД: не сопоставлено — нужно опознать работодателя по сумме/дате/паре с Копилкой"

    if "ozon" in d:
        # Решение Марии 27.09.2026: вся "сборная солянка" Ozon → Дом/продукты,
        # пока нет способа автовыгрузки состава заказа с самого Ozon.
        return "Дом/продукты"

    if any(k in d for k in ["перевод для", "перевод от", "перевод клиенту",
                             "перевод другому клиенту", "на счёт в другой банк"]):
        return "? уточнить: перевод физлицу"

    return "? уточнить: прочее (без описания)"


